/** Треугольник с вершиной в peak и полушириной half, обрезанный универсом. */
const triangle = (
  name: string,
  peak: number,
  half: number,
  universe: [number, number]
): Term => {
  const at = (x: number) => Math.max(0, 1 - Math.abs(x - peak) / half);
  const xs = [peak - half, peak, peak + half].filter(
    (x) => x > universe[0] && x < universe[1]
  );
  const points = [universe[0], ...xs, universe[1]]
    .filter((x, i, all) => all.indexOf(x) === i)
    .sort((a, b) => a - b)
    .map((x) => [x, Math.round(at(x) * 1e4) / 1e4] as [number, number]);

  return { name, points };
};

