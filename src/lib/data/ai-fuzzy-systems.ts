/** Терм, заданный формулой: точки — её кусочно-линейное приближение. */
const formulaTerm = (
  name: string,
  formula: string,
  exact: (x: number) => number,
  universe: [number, number],
  count = 7
): Term => ({
  name,
  formula,
  exact,
  points: piecewise(exact, universe[0], universe[1], count),
});

