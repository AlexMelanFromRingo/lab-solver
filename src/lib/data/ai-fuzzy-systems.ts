const term = (name: string, points: [number, number][], label?: Loc): Term => ({
  name,
  points,
  label,
});

const variable = (
  name: string,
  label: Loc,
  universe: [number, number],
  terms: Term[],
  unit?: Loc
): Variable => ({ name, label, universe, terms, unit });

/**
 * Таблица правил: имена входных переменных и строки, где последний столбец —
 * заключение. Пустая клетка означает, что переменная в правиле не участвует
 * (так записано правило «складність мала» в задании 3).
 */
const ruleTable = (inputs: string[], rows: string[][]): Rule[] =>
  rows.map((row) => ({
    when: inputs
      .map((name, i) => [name, row[i]] as [string, string])
      .filter(([, t]) => t !== ""),
    then: row[inputs.length],
  }));

export interface FuzzyCase {
  label: Loc;
  values: Record<string, number>;
}

export interface FuzzyTask {
  id: string;
  /** Номер задания в п. 4.3; 0 — разобранный пример п. 4.2. */
  variant: number;
  title: Loc;
  summary: Loc;
  system: FuzzySystem;
  /** Наборы, которые методичка предлагает исследовать. */
  cases: FuzzyCase[];
  /** Расхождения в тексте задания и принятое чтение. */
  notes: Loc[];
}

