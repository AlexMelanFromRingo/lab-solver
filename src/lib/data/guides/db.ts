/** Номер теми з Метод_БД_інд — однаковий для всіх робіт курсу. */
const TOPIC = (compute: (v: number) => GuideComputed): GuideVariant => ({
  label: "теми",
  min: 1,
  max: DB_TOPICS.length,
  hint: "Номер теми індивідуального завдання (Метод_БД_інд, п. 1.2): «ІМЕННИК1 — ДІЄСЛОВО — ІМЕННИК2». Та сама тема — в усіх лабораторних.",
  compute,
});

/** ЛР 3–6: таблиці бази за темою, з якими працюють оператори SQL. */
function dbSchema(v: number, notes: string[]): GuideComputed {
  const m = buildModel(v);
  const t = (x: DbTable, title: string) => ({
    title,
    columns: ["Поле", "Тип (Jet SQL)", "Ключ"],
    rows: x.fields.map((f) => [f.name, f.sql === "COUNTER" ? "INTEGER" : f.sql, f.key ? "так" : ""]),
  });
  return {
    tables: [t(m.t1, `ІМЕННИК_1: «${m.t1.name}»`), t(m.t3, `ДІЄСЛОВО: «${m.t3.name}»`), t(m.t2, `ІМЕННИК_2: «${m.t2.name}»`)],
    notes,
  };
}

