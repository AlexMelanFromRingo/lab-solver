function runBlock(code: string, inputs: (string | number)[]) {
  const r = execute(code, inputs);
  return { lines: r.output, text: r.output.join("\n") + (r.errors.length ? `\n${r.errors.join("\n")}` : "") };
}

const lastValue = (lines: string[]) => {
  for (let i = lines.length - 1; i >= 0; i--) {
    const v = printedValues(lines[i]);
    if (v.length) return v[v.length - 1];
  }
  return NaN;
};

