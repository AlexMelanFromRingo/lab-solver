function euclidComputed(a: number, b: number, label: string): GuideComputed {
  const e = euclid(a, b);
  return {
    tables: [
      {
        title: `Ділення за Евклідом: ${label}`,
        columns: ["Ділене", "Дільник", "Частка", "Остача", "Запис"],
        rows: e.rows.map((r) => [r.a, r.b, r.q, r.r, `${r.a} = ${r.b}·${r.q} + ${r.r}`]),
      },
    ],
    code: [
      {
        title: `Результат: ${label}`,
        code: [
          `НСД(${a}, ${b}) = ${e.gcd}`,
          `НСК(${a}, ${b}) = ${a}·${b} / ${e.gcd} = ${e.lcm}`,
          `Повна форма: ${a}/${b} = ${cfFull(e.cf)}`,
          `Коротка форма: ${a}/${b} = ${cfShort(e.cf)}`,
        ].join("\n"),
      },
    ],
  };
}

function extTable(x: ExtResult, title: string) {
  return {
    title,
    columns: ["Залишки", "Часткові", "x", "y"],
    rows: x.rows.map((r) => [r.r, r.q ?? "*", r.q === null ? r.x : r.xExpr || "*", r.q === null ? r.y : r.yExpr || "*"]),
  };
}

function merge(...parts: GuideComputed[]): GuideComputed {
  return {
    tables: parts.flatMap((p) => p.tables ?? []),
    figures: parts.flatMap((p) => p.figures ?? []),
    code: parts.flatMap((p) => p.code ?? []),
    notes: parts.flatMap((p) => p.notes ?? []),
  };
}

