/**
 * Расширенный полигон ЛР1 (рис. 1.5), он же — основа ЛР2. Адреса узлов
 * методичка оставляет на выбор; здесь они выбраны так, чтобы таблица
 * статического NAT из ЛР2 совпала с реальными узлами.
 */
function extended(v: number) {
  return {
    net1: `10.${v}.1.0/24`,
    net2: `10.${v}.2.0/24`,
    net3: `212.${v}.211.16/30`,
    net4: `200.10.${v}.0/24`,
    net5: `210.10.${v}.0/24`,
    rows: [
      ["Central", "FastEthernet0/0", "Net1", `10.${v}.1.1/24`],
      ["Central", "FastEthernet1/0", "Net2", `10.${v}.2.1/24`],
      ["Central", "Serial2/0", "Net3", `212.${v}.211.17/30`],
      ["ISP", "Serial2/0 (DCE, clock rate 128000)", "Net3", `212.${v}.211.18/30`],
      ["ISP", "FastEthernet0/0", "Net4", `200.10.${v}.1/24`],
      ["ISP", "FastEthernet1/0", "Net5", `210.10.${v}.1/24`],
      ["PC0", "", "Net1", `10.${v}.1.2/24, шлюз 10.${v}.1.1`],
      ["PC1 (консоль Central)", "", "Net1", `10.${v}.1.3/24, шлюз 10.${v}.1.1`],
      ["PC2", "", "Net2", `10.${v}.2.2/24, шлюз 10.${v}.2.1`],
      ["PC5", "", "Net2", `10.${v}.2.3/24, шлюз 10.${v}.2.1`],
      ["Server-DNS", "", "Net4", `200.10.${v}.2/24, шлюз 200.10.${v}.1`],
      ["PC4 (консоль ISP)", "", "Net4", `200.10.${v}.3/24, шлюз 200.10.${v}.1`],
      ["ServerHTTP", "", "Net5", `210.10.${v}.2/24, шлюз 210.10.${v}.1`],
    ] as string[][],
    central: [
      "enable",
      "configure terminal",
      "hostname Central",
      "interface FastEthernet0/0",
      ` ip address 10.${v}.1.1 255.255.255.0`,
      " no shutdown",
      "interface FastEthernet1/0",
      ` ip address 10.${v}.2.1 255.255.255.0`,
      " no shutdown",
      "interface Serial2/0",
      ` ip address 212.${v}.211.17 255.255.255.252`,
      " no shutdown",
      " exit",
      "ip route 0.0.0.0 0.0.0.0 Serial2/0",
      "end",
    ].join("\n"),
    isp: [
      "enable",
      "configure terminal",
      "hostname ISP",
      "interface Serial2/0",
      ` ip address 212.${v}.211.18 255.255.255.252`,
      " clock rate 128000",
      " no shutdown",
      "interface FastEthernet0/0",
      ` ip address 200.10.${v}.1 255.255.255.0`,
      " no shutdown",
      "interface FastEthernet1/0",
      ` ip address 210.10.${v}.1 255.255.255.0`,
      " no shutdown",
      " exit",
      "ip route 0.0.0.0 0.0.0.0 Serial2/0",
      "end",
    ].join("\n"),
  };
}

