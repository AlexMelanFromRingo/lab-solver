const LIST_COLS = ["Адреса", "Код", "Мнемокод", "Коментар"];

function lastByte(p: Program): number {
  let end = 0;
  for (const l of p.lines) if (l.bytes.length) end = Math.max(end, l.addr + l.bytes.length - 1);
  return end;
}

function haltAddr(p: Program): number {
  for (const l of p.lines) if (l.bytes[0] === 0x76) return l.addr;
  return lastByte(p);
}

// ---------------------------------------------------------------- ЛР 1

function lab1Program(n: number, k: number) {
  return assemble(`ORG 0805h
RES DB 00h          ; комірка для результату
MVI A,${hx(n)}h         ; A <- номер за журналом (${n})
MVI B,${hx(k)}h         ; B <- номер курсу (${k})
ADD B               ; A <- A + B
STA 0805h           ; результат -> 0805h
HLT`);
}

