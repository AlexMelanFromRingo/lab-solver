function lastByte(p: Program): number {
  let end = 0;
  for (const l of p.lines) if (l.bytes.length) end = Math.max(end, l.addr + l.bytes.length - 1);
  return end;
}

function haltAddr(p: Program): number {
  for (const l of p.lines) if (l.bytes[0] === 0x76) return l.addr;
  return lastByte(p);
}

