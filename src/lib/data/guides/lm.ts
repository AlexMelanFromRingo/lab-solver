const SRC = "Локальні мережі, методичні вказівки до лабораторних робіт";

function variantData(n: number): GuideComputed {
  const { infra: i, traffic: t } = lanVariant(n);
  const servers = t.file + t.http + t.ftp + t.db;
  return {
    tables: [
      {
        title: `Вариант ${n}: тип инфраструктуры ${i.type}, тип трафика ${t.type} (таблица 1.1)`,
        columns: ["Параметр", "Значение"],
        rows: [
          ["Зданий", i.buildings],
          ["Расстояние между зданиями", `${i.distance} м`],
          ["Этажей в здании", i.floors],
          ["Комнат на этаже", i.rooms],
          ["Всего комнат", i.buildings * i.floors * i.rooms],
          ["Файловых серверов", t.file],
          ["HTTP-серверов", t.http],
          ["FTP-серверов", t.ftp],
          ["Серверов баз данных (Small office database server)", t.db],
          ["Всего серверов в серверной комнате", servers],
        ],
        note:
          "Дополнительные данные примера — ширина этажа 18 м, высота 3 м; условия эксперимента во всех работах одинаковы: " +
          "модель работает 7 минут, пакеты 500–1000 байт каждые 0,02 с по экспоненциальному закону.",
      },
    ],
  };
}

const TITLES: Record<LanLab, string> = {
  e1: "Ethernet",
  e2: "Switched Ethernet",
  e3: "Fast Ethernet",
  e4: "Switched Fast Ethernet",
  m1: "Token Ring",
  m2: "Switched Token Ring",
  m3: "FDDI",
};

/**
 * Обладнання за структурою сайту (серверна будівля + по пристрою в кожній іншій): для Switched Ethernet і
 * Switched Fast Ethernet комутатор стоїть у серверній, до його портів — усі сервери й хаби (повторювачі)
 * кожної будівлі. Приклад методички (варіант 43: 8 серверів, 3 будівлі) — 11 портів і 11 доменів колізій,
 * з них 9 мідних і 2 оптичні.
 */
function equipment(n: number, lab: LanLab): GuideComputed["tables"] {
  const { infra: i, traffic: t } = lanVariant(n);
  const servers = t.file + t.http + t.ftp + t.db;
  const remote = i.buildings - 1;
  if (lab === "e2" || lab === "e4") {
    const fast = lab === "e4";
    const tx = fast ? "100Base-TX" : "10Base-T";
    const fx = fast ? "100Base-FX" : "10Base-FL";
    const hub = fast ? { one: "Повторювач I класу", of: "повторювач I класу", pl: "повторювачі", ins: "повторювачами" } : { one: "Хаб", of: "хаб", pl: "хаби", ins: "хабами" };
    const domain = fast ? { pl: "зон конфлікту", one: "окрема зона конфлікту" } : { pl: "доменів колізій", one: "окремий домен колізій" };
    return [
      {
        title: "Обґрунтування кількості комунікаційного устаткування",
        columns: ["Устаткування", "Кількість", "Чому"],
        rows: [
          [`Комутатор ${fast ? "Fast Ethernet" : "Ethernet"}`, 1, "у Building (1) — серверній, де найбільше завантаження (як у прикладі)"],
          [hub.one, i.buildings, `по одному в кожній будівлі; до нього — станції будівлі (${tx})`],
          [`Порти ${tx} комутатора`, servers + 1, `${servers} серверів напряму + ${hub.of} серверної будівлі`],
          [`Порти ${fx} комутатора`, remote, `${hub.pl} будівель 2–${i.buildings}, кабель кампусу ${i.distance} м`],
          [`Усього портів / ${domain.pl}`, servers + i.buildings, `кожен порт — ${domain.one}: ${servers} із серверами і ${i.buildings} з ${hub.ins}`],
        ],
        note: "Модель комутатора — з методички; добирайте модулі так, щоб портів вистачило (у прикладі DEC switch 400: 8 + 1 портів 10Base-T і 2 модулі 10Base-F).",
      },
    ];
  }
  if (lab === "m1") {
    const direct = i.distance + 7;
    return [
      {
        title: "Перевірка обмежень Token Ring",
        columns: ["Обмеження", "Значення варіанта", "Висновок"],
        rows: [
          ["Довжина сегмента при прямому підключенні станцій до кільця ≤ 100 м", `${i.distance} + 7 = ${direct} м`, direct > 100 ? "перевищує — потрібна фізична структуризація концентраторами MSAU" : "вкладається"],
          ["Кабель між концентраторами ≤ 45 м", `між будівлями ${i.distance} м`, i.distance > 45 ? "довше — між будівлями потрібні проміжні концентратори або оптичні повторювачі (у прикладі — 16 Meg Token Ring Repeater Module)" : "вкладається"],
          ["Концентраторів у будівлях", i.buildings, `по MSAU у кожній будівлі; сервери (${servers}) — до MSAU серверної`],
        ],
      },
    ];
  }
  if (lab === "m3") {
    const ring = i.buildings * i.distance;
    return [
      {
        title: "Перевірка обмежень FDDI",
        columns: ["Обмеження", "Значення варіанта", "Висновок"],
        rows: [
          ["Між сусідніми вузлами по багатомодовому волокну ≤ 2 км", `${i.distance} м`, "вкладається"],
          ["Довжина кільця ≤ 100 км", `${i.buildings} × ${i.distance} = ${ring} м`, "вкладається"],
          ["Концентраторів FDDI (DAC) на подвійному кільці", i.buildings, `по одному в будівлі; ${servers} серверів — до концентратора серверної (SAS)`],
        ],
      },
    ];
  }
  return undefined;
}

const variantFor = (lab: LanLab): GuideVariant => ({
  label: "варианта",
  min: 1,
  max: 80,
  hint: "Номер варианта индивидуального задания выдаёт преподаватель; по таблице 1.1 он даёт тип инфраструктуры и тип трафика.",
  compute: (n) => {
    const base = variantData(n);
    return {
      ...base,
      tables: [...(base.tables ?? []), ...(equipment(n, lab) ?? [])],
      figures: [
        {
          kind: "drawing",
          title: `Структура мережі ${TITLES[lab]} з відстанями, місцем серверів і устаткування (варіант ${n})`,
          drawing: lanStructure(n, lab),
          note: "Серверна — в центральному здании, остальные здания — лучами на расстоянии варианта (как в примере методички). Число станций по комнатам — из найденного порога.",
        },
      ],
    };
  },
});

