const SRC = "Локальні мережі, методичні вказівки до лабораторних робіт";

function variantData(n: number): GuideComputed {
  const { infra: i, traffic: t } = lanVariant(n);
  const servers = t.file + t.http + t.ftp + t.db;
  return {
    tables: [
      {
        title: `Вариант ${n}: тип инфраструктуры ${i.type}, тип трафика ${t.type} (таблица 1.1)`,
        columns: ["Параметр", "Значение"],
        rows: [
          ["Зданий", i.buildings],
          ["Расстояние между зданиями", `${i.distance} м`],
          ["Этажей в здании", i.floors],
          ["Комнат на этаже", i.rooms],
          ["Всего комнат", i.buildings * i.floors * i.rooms],
          ["Файловых серверов", t.file],
          ["HTTP-серверов", t.http],
          ["FTP-серверов", t.ftp],
          ["Серверов баз данных (Small office database server)", t.db],
          ["Всего серверов в серверной комнате", servers],
        ],
        note:
          "Дополнительные данные примера — ширина этажа 18 м, высота 3 м; условия эксперимента во всех работах одинаковы: " +
          "модель работает 7 минут, пакеты 500–1000 байт каждые 0,02 с по экспоненциальному закону.",
      },
    ],
  };
}

