function formulaNotes(f: Formula): string[] {
  const rows = truthTable(f);
  const dummy = dummyVars(f);
  const ones = rows.filter((r) => r.out).length;
  const notes: string[] = [];
  if (ones === 0 || ones === rows.length)
    notes.push(`Формула тождественно равна ${ones ? 1 : 0}: на выходе ${f.out} при моделировании будет постоянный уровень при любых входах.`);
  else if (dummy.length)
    notes.push(
      `${f.out} не зависит от ${dummy.join(", ")}: ${dummy.length > 1 ? "эти переменные на выход не влияют" : "эта переменная на выход не влияет"}. Схема всё равно строится по формуле как записана — так требует задание.`,
    );
  return notes;
}

