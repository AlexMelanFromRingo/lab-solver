function formulaNotes(f: Formula): string[] {
  const rows = truthTable(f);
  const dummy = dummyVars(f);
  const ones = rows.filter((r) => r.out).length;
  const notes: string[] = [];
  if (ones === 0 || ones === rows.length)
    notes.push(`Формула тождественно равна ${ones ? 1 : 0}: на выходе ${f.out} при моделировании будет постоянный уровень при любых входах.`);
  else if (dummy.length)
    notes.push(
      `${f.out} не зависит от ${dummy.join(", ")}: ${dummy.length > 1 ? "эти переменные на выход не влияют" : "эта переменная на выход не влияет"}. Схема всё равно строится по формуле как записана — так требует задание.`,
    );
  return notes;
}

function gateTable(f: Formula): GuideTable {
  const { gates } = buildGates(f);
  return {
    title: `Компоненти (бібліотека 7400.olb) — ${gates.length} шт.`,
    columns: ["Позначення", "Мікросхема", "Функція", "Входи", "Вихід"],
    rows: gates.map((g) => [g.ref, g.part, g.title, g.inputs.join(", "), g.output]),
    note: "N1, N2… — проміжні кола (у Capture без Net Alias вони отримають імена N0xxxx). Кожен елемент — окремий компонент із секцією A, як U1A–U4A у прикладі методички.",
  };
}

function truthTableOf(f: Formula): GuideTable {
  return {
    title: "Таблиця істинності",
    columns: [...f.vars, f.out],
    rows: truthTable(f).map((r) => [...r.inputs, r.out]),
  };
}

