/** Послідовність клавіш УМК: «П», адреса, байти через клавішу переходу (_), «ВП». */
function enterKeys(p: Program, from: number, to: number) {
  const bytes: string[] = [];
  for (let x = from; x <= to; x++) bytes.push(hx(p.mem.get(x) ?? 0));
  return `П ${hx(from, 4)} ${bytes.join(" _ ")} ВП`;
}


