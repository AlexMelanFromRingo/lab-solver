const REG_DATA = [1, 2, 3, 1, 0, 2, 1, 3, 0];

function stepsText(mode: Mode, from: number, to: number) {
  const steps = transition(mode, from, to);
  const q = steps.filter((s, i) => i === 0 || s.q !== steps[i - 1].q);
  const y = steps.filter((s, i) => i === 0 || s.y !== steps[i - 1].y);
  const qs = q.map((s, i) => (i ? `${bin(s.q, 2)} (${s.t} нс)` : bin(s.q, 2))).join(" → ");
  const ys = y.map((s, i) => (i ? `${hex(s.y)} (${s.t} нс)` : hex(s.y))).join(" → ");
  const falseQ = q.slice(1, -1).map((s) => s.q);
  const falseY = y.slice(1, -1).map((s) => hex(s.y));
  return { qs, ys, falseQ, falseY };
}

function lab6Tables(tUs: number): GuideTable[] {
  const up = sequence("up", 9);
  const down = sequence("down", 9);
  const reg = sequence("reg", 9, REG_DATA);
  const edge = (k: number) => n(tUs / 2 + k * tUs, 3);
  const y = (q: number) => hex(Number(transition("reg", q, q).at(-1)!.y));
  const glitchRows = (mode: Mode, seq: number[]) => {
    const seen = new Set<string>();
    const rows: (string | number)[][] = [];
    let prev = 0;
    for (const q of seq) {
      const key = `${prev}>${q}`;
      if (!seen.has(key) && prev !== q) {
        seen.add(key);
        const s = stepsText(mode, prev, q);
        rows.push([`${prev} → ${q}`, s.qs, s.falseQ.length ? s.falseQ.join(", ") : "—", s.ys, s.falseY.length ? s.falseY.join(", ") : "—"]);
      }
      prev = q;
    }
    return rows;
  };
  const cols = ["Перехід", "Шина Q (Q1Q0)", "Хибні Q", "Шина Y (hex)", "Хибні Y"];
  return [
    {
      title: `Стани по фронтах Clk (період ${n(tUs)} мкс, моделювання 9 періодів = ${n(9 * tUs)} мкс)`,
      columns: ["Фронт", "t, мкс", "Q ↑ (підсумовуючий)", "Y ↑", "Q ↓ (віднімаючий)", "Y ↓", "D", "Q (регістр)", "Y (регістр)"],
      rows: up.map((q, k) => [k + 1, edge(k), `${q} (${bin(q, 2)})`, y(q), `${down[k]} (${bin(down[k], 2)})`, y(down[k]), REG_DATA[k], `${reg[k]} (${bin(reg[k], 2)})`, y(reg[k])]),
      note: "До першого фронту Rst = 0 — обидва тригери скинуті, Q = 0, Y = E (1110). Перший фронт Rising — через T/2 після старту (Clock починається з нуля).",
    },
    { title: "Підсумовуючий лічильник — хибні комбінації після фронту", columns: cols, rows: glitchRows("up", up) },
    { title: "Віднімаючий лічильник — хибні комбінації", columns: cols, rows: glitchRows("down", down) },
    { title: "Регістр — хибні комбінації", columns: cols, rows: glitchRows("reg", reg) },
  ];
}

