function planTable(s: Step, a: number[], b: number[], c: number[][], title: string): GuideTable {
  const rows = s.x.map((r, i) => [
    `A${i + 1}${i >= 3 ? " (фикт.)" : ""}${s.u ? `  u=${s.u[i] ?? "—"}` : ""}`,
    ...r.map((v, j) => {
      const d = s.delta?.[i][j];
      const mark = s.cycle ? s.cycle.findIndex(([ci, cj]) => ci === i && cj === j) : -1;
      const sign = mark < 0 ? "" : mark % 2 ? " (−)" : " (+)";
      return v !== null ? `${v} | c=${c[i][j]}${sign}` : `c=${c[i][j]}${d !== undefined && d !== null ? `, Δ=${d}` : ""}${sign}`;
    }),
    a[i],
  ]);
  rows.push(["Потреби", ...b, a.reduce((x, y) => x + y, 0)]);
  return {
    title: `${title} — затраты ${s.cost}`,
    columns: ["", ...b.map((_, j) => `B${j + 1}${j >= 5 ? " (фикт.)" : ""}${s.v ? `  v=${s.v[j] ?? "—"}` : ""}`), "Запаси"],
    rows,
  };
}

