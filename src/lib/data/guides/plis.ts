const v28 = (hint: string) => ({ label: "варианта", min: 1, max: 28, hint });

function truth(v: number): GuideTable {
  const f = formula(v);
  return { title: "Таблиця істинності", columns: [...f.vars, f.out], rows: truthTable(f).map((r) => [...r.inputs, r.out]) };
}

function formulaNote(v: number): string[] {
  const f = formula(v);
  const rows = truthTable(f);
  const ones = rows.filter((r) => r.out).length;
  if (ones === 0 || ones === rows.length) return [`Формула тотожно дорівнює ${ones ? 1 : 0} — синтезатор зведе схему до константи, на RTL Schematic елементів не лишиться.`];
  const d = dummyVars(f);
  return d.length ? [`${f.out} не залежить від ${d.join(", ")} — синтезатор цей вхід відкине (у звіті синтезу — попередження про невикористаний вхід).`] : [];
}

