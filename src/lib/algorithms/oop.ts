/** Формулы (1) и (2): A = Pвл − 0,5·(tсух − tвл)·B/1006, R = A/Pсух·100 %. */
export function humidity(tDry: number, tWet: number, b: number, alpha = 0.5) {
  const pDry = saturation(tDry);
  const pWet = saturation(tWet);
  const a = pWet - (alpha * (tDry - tWet) * b) / 1006;
  return { pDry, pWet, a, r: (a / pDry) * 100, table: psychroTable(tWet, tDry - tWet) };
}

