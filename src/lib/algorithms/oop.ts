/** Pd = P − Ps; V = √(2g·Pd/ρ); L = 3600·V·A; W = P·L/(3600·120·η); n = L/Vп. */
export function ventilation(p: number, ps: number, a = 0.04, rho = 1.2, eta = 0.5, room = 45) {
  const pd = p - ps;
  const v = Math.sqrt((2 * 9.81 * pd) / rho);
  const l = 3600 * v * a;
  const w = (p * l) / (3600 * 120 * eta);
  return { pd, v, l, w, n: l / room };
}
