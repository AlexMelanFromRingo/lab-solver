export type UIKey = keyof typeof UI;

export function ui(key: UIKey, lang: Lang): string {
  return UI[key][lang];
}

/** «Номер ціле число від a до b» — текст помилки варіанта. */
export function errRange(label: string, a: number, b: number, lang: Lang): string {
  return lang === "uk" ? `${label} — ціле число від ${a} до ${b}` : `${label} — целое число от ${a} до ${b}`;
}

/** Підпис поля «Номер варіанта» / «Номер теми». */
export function numLabel(label: string, lang: Lang): string {
  return `Номер ${label}`;
}

