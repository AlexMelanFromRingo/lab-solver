/** Слово «модуль» з числом. */
export function modulesWord(n: number, lang: Lang): string {
  const d = n % 10, h = n % 100;
  if (lang === "uk") return d === 1 && h !== 11 ? "модуль" : d >= 2 && d <= 4 && (h < 12 || h > 14) ? "модулі" : "модулів";
  return d === 1 && h !== 11 ? "модуль" : d >= 2 && d <= 4 && (h < 12 || h > 14) ? "модуля" : "модулей";
}
