const LEVELS = [2, 5, 8, 11, 13];

/** Потенціал у точці за еквіпотенціалями: у кожному стовпці x лінійна інтерполяція між лініями. */
function potential(xs: number[], ys: number[][], x: number, y: number): number {
  if (x < xs[0] || x > xs[xs.length - 1]) return NaN;
  let j = xs.findIndex((v, i) => i < xs.length - 1 && x >= v && x <= xs[i + 1]);
  if (j < 0) j = xs.length - 2;
  const u = (x - xs[j]) / (xs[j + 1] - xs[j]);
  const yk = ys.map((col) => col[j] + u * (col[j + 1] - col[j]));
  for (let k = 0; k < yk.length - 1; k++) {
    const [a, b] = [yk[k], yk[k + 1]];
    if ((y <= a && y >= b) || (y >= a && y <= b)) return LEVELS[k] + ((y - a) / (b - a)) * (LEVELS[k + 1] - LEVELS[k]);
  }
  return NaN;
}

function fieldLine(xs: number[], ys: number[][], x0: number, y0: number): [number, number][] {
  const out: [number, number][] = [[x0, y0]];
  let [x, y] = [x0, y0];
  const h = 0.05;
  for (let s = 0; s < 400; s++) {
    const gx = (potential(xs, ys, x + h, y) - potential(xs, ys, x - h, y)) / (2 * h);
    const gy = (potential(xs, ys, x, y + h) - potential(xs, ys, x, y - h)) / (2 * h);
    const n = Math.hypot(gx, gy);
    if (!Number.isFinite(n) || n === 0) break;
    x -= (0.25 * gx) / n;
    y -= (0.25 * gy) / n;
    if (!Number.isFinite(potential(xs, ys, x, y))) break;
    out.push([x, y]);
  }
  return out;
}

