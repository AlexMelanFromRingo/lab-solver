export function oberbeckTheory(r: number) {
  const ic = (0.023 * 0.15 ** 2) / 12; // спиця 150 мм, 23 г
  const i0 = 0.12 * (0.015 ** 2 / 4 + 0.02 ** 2 / 12); // циліндр 120 г, R 1,5 см, h 2 см, вісь поперек
  return 2 * ic + 4 * (i0 + 0.12 * r * r);
}

