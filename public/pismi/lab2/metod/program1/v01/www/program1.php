<?php
// Лабораторна робота № 2. Програма № 1: обчислення функцій y1 та y2.
// Варіант 1:
//   y₁ = sin⁴x + cos⁴x
//   y₂ = ((1 − cos 2x) / 2)² + ((1 + cos 2x) / 2)²
//   де x = 0,4985
//
// У методичних вказівках обидва доданки y₂ надруковані однаково, з (1 −
// cos 2x). Це помилка набору: другий доданок замінює cos²x, тому в ньому
// має стояти (1 + cos 2x). З надрукованим виразом рівність не виконується
// в жодній точці.

function y1($x)
{
    return sin($x) ** 4 + cos($x) ** 4;
}

function y2($x)
{
    return ((1 - cos(2 * $x)) / 2) ** 2 + ((1 + cos(2 * $x)) / 2) ** 2;
}

// Вхідні дані
$x = 0.4985;

$y1 = y1($x);
$y2 = y2($x);

echo "<h1>Лабораторна робота № 2. Програма № 1</h1>";
echo "<p>y₁ = sin⁴x + cos⁴x</p>";
echo "<p>y₂ = ((1 − cos 2x) / 2)² + ((1 + cos 2x) / 2)²</p>";
echo "<p>Вхідні дані: x = $x</p>";
echo "<p>y1 = $y1</p>";
echo "<p>y2 = $y2</p>";

// Значення обчислено різними шляхами, тому вони порівнюються з допуском
if (abs($y1 - $y2) < 1e-9) {
    echo "<p>y1 = y2, результати збігаються.</p>";
} else {
    echo "<p>y1 ≠ y2, результати не збігаються.</p>";
}
