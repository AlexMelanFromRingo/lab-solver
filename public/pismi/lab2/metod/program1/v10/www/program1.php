<?php
// Лабораторна робота № 2. Програма № 1: обчислення функцій y1 та y2.
// Варіант 10:
//   y₁ = ((x − 1)(x^1,5 − 1)) / ((x + √x + 1)(x^0,5 + 1)) + 2 / x^(−0,5)
//   y₂ = x + 1
//   де x = 5,55

function y1($x)
{
    $r = sqrt($x);
    $frac = (($x - 1) * ($x ** 1.5 - 1)) / (($x + $r + 1) * ($r + 1));

    return $frac + 2 / $x ** -0.5;
}

function y2($x)
{
    return $x + 1;
}

// Вхідні дані
$x = 5.55;

$y1 = y1($x);
$y2 = y2($x);

echo "<h1>Лабораторна робота № 2. Програма № 1</h1>";
echo "<p>y₁ = ((x − 1)(x^1,5 − 1)) / ((x + √x + 1)(x^0,5 + 1)) + 2 / x^(−0,5)</p>";
echo "<p>y₂ = x + 1</p>";
echo "<p>Вхідні дані: x = $x</p>";
echo "<p>y1 = $y1</p>";
echo "<p>y2 = $y2</p>";

// Значення обчислено різними шляхами, тому вони порівнюються з допуском
if (abs($y1 - $y2) < 1e-9) {
    echo "<p>y1 = y2, результати збігаються.</p>";
} else {
    echo "<p>y1 ≠ y2, результати не збігаються.</p>";
}
