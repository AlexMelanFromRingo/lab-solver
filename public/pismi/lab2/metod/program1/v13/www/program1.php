<?php
// Лабораторна робота № 2. Програма № 1: обчислення функцій y1 та y2.
// Варіант 13:
//   y₁ = (1 − a⁻²)/(√a − a^(−0,5)) − 2/√(a³) + (a⁻² − a)/(√a − a^(−0,5))
//   y₂ = −√a − 2·a^(−1,5)
//   де a = 12,7

function y1($a)
{
    $den = sqrt($a) - $a ** -0.5;
    $first = (1 - $a ** -2) / $den;
    $third = ($a ** -2 - $a) / $den;

    return $first - 2 / sqrt($a ** 3) + $third;
}

function y2($a)
{
    return -sqrt($a) - 2 * $a ** -1.5;
}

// Вхідні дані
$a = 12.7;

$y1 = y1($a);
$y2 = y2($a);

echo "<h1>Лабораторна робота № 2. Програма № 1</h1>";
echo "<p>y₁ = (1 − a⁻²)/(√a − a^(−0,5)) − 2/√(a³) + (a⁻² − a)/(√a − a^(−0,5))</p>";
echo "<p>y₂ = −√a − 2·a^(−1,5)</p>";
echo "<p>Вхідні дані: a = $a</p>";
echo "<p>y1 = $y1</p>";
echo "<p>y2 = $y2</p>";

// Значення обчислено різними шляхами, тому вони порівнюються з допуском
if (abs($y1 - $y2) < 1e-9) {
    echo "<p>y1 = y2, результати збігаються.</p>";
} else {
    echo "<p>y1 ≠ y2, результати не збігаються.</p>";
}
