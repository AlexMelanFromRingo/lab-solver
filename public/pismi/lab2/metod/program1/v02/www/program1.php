<?php
// Лабораторна робота № 2. Програма № 1: обчислення функцій y1 та y2.
// Варіант 2:
//   y₁ = a·cos x + b·sin x
//   y₂ = A·sin(x + μ),   A = √(a² + b²),   μ = arcsin(a / √(a² + b²))
//   де a = 5,5; b = 12,7; x = 1,28

function y1($a, $b, $x)
{
    return $a * cos($x) + $b * sin($x);
}

function y2($a, $b, $x)
{
    $amp = sqrt($a ** 2 + $b ** 2);
    $mu = asin($a / $amp);

    return $amp * sin($x + $mu);
}

// Вхідні дані
$a = 5.5;
$b = 12.7;
$x = 1.28;

$y1 = y1($a, $b, $x);
$y2 = y2($a, $b, $x);

echo "<h1>Лабораторна робота № 2. Програма № 1</h1>";
echo "<p>y₁ = a·cos x + b·sin x</p>";
echo "<p>y₂ = A·sin(x + μ),   A = √(a² + b²),   μ = arcsin(a / √(a² + b²))</p>";
echo "<p>Вхідні дані: a = $a, b = $b, x = $x</p>";
echo "<p>y1 = $y1</p>";
echo "<p>y2 = $y2</p>";

// Значення обчислено різними шляхами, тому вони порівнюються з допуском
if (abs($y1 - $y2) < 1e-9) {
    echo "<p>y1 = y2, результати збігаються.</p>";
} else {
    echo "<p>y1 ≠ y2, результати не збігаються.</p>";
}
