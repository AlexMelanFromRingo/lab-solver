<?php
// Лабораторна робота № 2. Програма № 1: обчислення функцій y1 та y2.
// Варіант 14:
//   y₁ = (√a/2 − 1/(2√a))² · ((√a − 1)/(√a + 1) − (√a + 1)/(√a − 1))
//   y₂ = (1 − a)/√a
//   де a = 50,765

function y1($a)
{
    $r = sqrt($a);
    $square = ($r / 2 - 1 / (2 * $r)) ** 2;
    $bracket = ($r - 1) / ($r + 1) - ($r + 1) / ($r - 1);

    return $square * $bracket;
}

function y2($a)
{
    return (1 - $a) / sqrt($a);
}

// Вхідні дані
$a = 50.765;

$y1 = y1($a);
$y2 = y2($a);

echo "<h1>Лабораторна робота № 2. Програма № 1</h1>";
echo "<p>y₁ = (√a/2 − 1/(2√a))² · ((√a − 1)/(√a + 1) − (√a + 1)/(√a − 1))</p>";
echo "<p>y₂ = (1 − a)/√a</p>";
echo "<p>Вхідні дані: a = $a</p>";
echo "<p>y1 = $y1</p>";
echo "<p>y2 = $y2</p>";

// Значення обчислено різними шляхами, тому вони порівнюються з допуском
if (abs($y1 - $y2) < 1e-9) {
    echo "<p>y1 = y2, результати збігаються.</p>";
} else {
    echo "<p>y1 ≠ y2, результати не збігаються.</p>";
}
