<?php
// Лабораторна робота № 2. Програма № 1: обчислення функцій y1 та y2.
// Варіант 7:
//   y₁ = 64·cos³(π/6 − α/2) · sin³(π/3 − α/2)
//   y₂ = (sin(3a/2) / sin(a/2))³
//   де a = 0,777

function y1($a)
{
    return 64 * cos(M_PI / 6 - $a / 2) ** 3
        * sin(M_PI / 3 - $a / 2) ** 3;
}

function y2($a)
{
    return (sin(1.5 * $a) / sin($a / 2)) ** 3;
}

// Вхідні дані
$a = 0.777;

$y1 = y1($a);
$y2 = y2($a);

echo "<h1>Лабораторна робота № 2. Програма № 1</h1>";
echo "<p>y₁ = 64·cos³(π/6 − α/2) · sin³(π/3 − α/2)</p>";
echo "<p>y₂ = (sin(3a/2) / sin(a/2))³</p>";
echo "<p>Вхідні дані: a = $a</p>";
echo "<p>y1 = $y1</p>";
echo "<p>y2 = $y2</p>";

// Значення обчислено різними шляхами, тому вони порівнюються з допуском
if (abs($y1 - $y2) < 1e-9) {
    echo "<p>y1 = y2, результати збігаються.</p>";
} else {
    echo "<p>y1 ≠ y2, результати не збігаються.</p>";
}
