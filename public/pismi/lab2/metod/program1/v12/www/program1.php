<?php
// Лабораторна робота № 2. Програма № 1: обчислення функцій y1 та y2.
// Варіант 12:
//   y₁ = √((1 − cos α)/(1 + cos α)) − √((1 + cos α)/(1 − cos α))
//   y₂ = 2 / tg α
//   де α = 4,987
//
// Знак результату залежить від чверті, у яку потрапляє α/2. Для інших
// значень α той самий вираз дасть −2/tg α, тому переносити відповідь на
// довільне α не можна.

function y1($alpha)
{
    $down = sqrt((1 - cos($alpha)) / (1 + cos($alpha)));
    $up = sqrt((1 + cos($alpha)) / (1 - cos($alpha)));

    return $down - $up;
}

function y2($alpha)
{
    return 2 / tan($alpha);
}

// Вхідні дані
$alpha = 4.987;

$y1 = y1($alpha);
$y2 = y2($alpha);

echo "<h1>Лабораторна робота № 2. Програма № 1</h1>";
echo "<p>y₁ = √((1 − cos α)/(1 + cos α)) − √((1 + cos α)/(1 − cos α))</p>";
echo "<p>y₂ = 2 / tg α</p>";
echo "<p>Вхідні дані: α = $alpha</p>";
echo "<p>y1 = $y1</p>";
echo "<p>y2 = $y2</p>";

// Значення обчислено різними шляхами, тому вони порівнюються з допуском
if (abs($y1 - $y2) < 1e-9) {
    echo "<p>y1 = y2, результати збігаються.</p>";
} else {
    echo "<p>y1 ≠ y2, результати не збігаються.</p>";
}
