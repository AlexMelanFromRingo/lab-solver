<?php
// Лабораторна робота № 2. Програма № 1: обчислення функцій y1 та y2.
// Варіант 11:
//   y₁ = t·(1 + 2/√(t+4)) / (2 − √(t+4)) + √(t+4) + 4/√(t+4) + t
//   y₂ = t − 4
//   де t = −3,57

function y1($t)
{
    $u = sqrt($t + 4);
    $first = $t * (1 + 2 / $u) / (2 - $u);

    return $first + $u + 4 / $u + $t;
}

function y2($t)
{
    return $t - 4;
}

// Вхідні дані
$t = -3.57;

$y1 = y1($t);
$y2 = y2($t);

echo "<h1>Лабораторна робота № 2. Програма № 1</h1>";
echo "<p>y₁ = t·(1 + 2/√(t+4)) / (2 − √(t+4)) + √(t+4) + 4/√(t+4) + t</p>";
echo "<p>y₂ = t − 4</p>";
echo "<p>Вхідні дані: t = $t</p>";
echo "<p>y1 = $y1</p>";
echo "<p>y2 = $y2</p>";

// Значення обчислено різними шляхами, тому вони порівнюються з допуском
if (abs($y1 - $y2) < 1e-9) {
    echo "<p>y1 = y2, результати збігаються.</p>";
} else {
    echo "<p>y1 ≠ y2, результати не збігаються.</p>";
}
