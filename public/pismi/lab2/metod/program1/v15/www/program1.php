<?php
// Лабораторна робота № 2. Програма № 1: обчислення функцій y1 та y2.
// Варіант 15:
//   y₁ = (1 − sin²(3π/2 + x)) / (1 − sin²(π + x))
//   y₂ = tg²x
//   де x = −0,789

function y1($x)
{
    $top = 1 - sin(3 * M_PI / 2 + $x) ** 2;
    $bottom = 1 - sin(M_PI + $x) ** 2;

    return $top / $bottom;
}

function y2($x)
{
    return tan($x) ** 2;
}

// Вхідні дані
$x = -0.789;

$y1 = y1($x);
$y2 = y2($x);

echo "<h1>Лабораторна робота № 2. Програма № 1</h1>";
echo "<p>y₁ = (1 − sin²(3π/2 + x)) / (1 − sin²(π + x))</p>";
echo "<p>y₂ = tg²x</p>";
echo "<p>Вхідні дані: x = $x</p>";
echo "<p>y1 = $y1</p>";
echo "<p>y2 = $y2</p>";

// Значення обчислено різними шляхами, тому вони порівнюються з допуском
if (abs($y1 - $y2) < 1e-9) {
    echo "<p>y1 = y2, результати збігаються.</p>";
} else {
    echo "<p>y1 ≠ y2, результати не збігаються.</p>";
}
