<?php
// Лабораторна робота № 2. Програма № 1: обчислення функцій y1 та y2.
// Варіант 5:
//   y₁ = (sin 3a · cos³a + cos 3a · sin³a) / 3
//   y₂ = sin 4a / 4
//   де a = −0,4224

function y1($a)
{
    return (sin(3 * $a) * cos($a) ** 3
        + cos(3 * $a) * sin($a) ** 3) / 3;
}

function y2($a)
{
    return sin(4 * $a) / 4;
}

// Вхідні дані
$a = -0.4224;

$y1 = y1($a);
$y2 = y2($a);

echo "<h1>Лабораторна робота № 2. Програма № 1</h1>";
echo "<p>y₁ = (sin 3a · cos³a + cos 3a · sin³a) / 3</p>";
echo "<p>y₂ = sin 4a / 4</p>";
echo "<p>Вхідні дані: a = $a</p>";
echo "<p>y1 = $y1</p>";
echo "<p>y2 = $y2</p>";

// Значення обчислено різними шляхами, тому вони порівнюються з допуском
if (abs($y1 - $y2) < 1e-9) {
    echo "<p>y1 = y2, результати збігаються.</p>";
} else {
    echo "<p>y1 ≠ y2, результати не збігаються.</p>";
}
