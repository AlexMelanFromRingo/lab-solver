 * не правки в чотирьох місцях.
 *
 * Поле описується так:
 *   name     ім'я стовпця в базі та поля форми;
 *   label    підпис у формі й заголовок стовпця таблиці;
 *   type     text | int | decimal | date | time | enum;
 *   sql      оголошення стовпця в CREATE TABLE;
 *   options  перелік допустимих значень (лише для enum);
 *   min, max межі (для int та decimal);
 *   wide     true, якщо поле довге й потребує широкого рядка введення.
 */

/**
 * Опис поля: коротка форма запису, щоб схема читалася як дані.
 *
 * @param array<string, mixed> $extra
 * @return array<string, mixed>
 */
function field(string $name, string $label, string $type, string $sql, array $extra = []): array
{
    return array_merge(
        ['name' => $name, 'label' => $label, 'type' => $type, 'sql' => $sql],
        $extra
    );
}

